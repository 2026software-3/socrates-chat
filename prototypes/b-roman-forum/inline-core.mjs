// Inlines forum-core.js into each proposal page so the pages open straight from
// file:// (browsers refuse module imports of local files) and publish as single files.
// Edit forum-core.js, then run: node prototypes/b-roman-forum/inline-core.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const START = '/* forum-core:start (generated by inline-core.mjs, edit forum-core.js) */';
const END = '/* forum-core:end */';

const core = readFileSync(join(dir, 'forum-core.js'), 'utf8');
const names = [];
const body = core
  .replace(/^import \* as THREE from 'three';\n/m, '')
  .replace(/^export \{ THREE \};\n/m, '')
  .replace(/^export (const|function) (\w+|\$)/gm, (_, kind, name) => {
    names.push(name);
    return `${kind} ${name}`;
  });
// The core runs in its own function scope so its private helpers cannot clash with page code.
const block = [
  START,
  "import * as THREE from 'three';",
  `const { ${names.join(', ')} } = (() => {`,
  body.trimEnd(),
  `return { ${names.join(', ')} };`,
  '})();',
  END,
].join('\n');

const importLine = /^import \{[^}]+\} from '\.\/forum-core\.js';$/m;
const existing = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')}`);

for (const page of ['vedute.html', 'moneta.html', 'salve.html']) {
  const path = join(dir, page);
  const html = readFileSync(path, 'utf8');
  let next;
  if (existing.test(html)) next = html.replace(existing, () => block);
  else if (importLine.test(html)) next = html.replace(importLine, () => block);
  else throw new Error(`${page}: no forum-core import or inlined block found`);
  writeFileSync(path, next);
  console.log(`${page}: inlined ${names.length} exports`);
}
